"""
TruthLens AI - Real ISOT Model Benchmarking (Phase 7)

Benchmarks only. This script NEVER writes data/saved_model_artifacts.json.

It expects Phase 2 preparation outputs in data/isot_prepared/, generated by
scripts/isot_data_pipeline.py, and the raw ISOT CSVs in data/.
"""

import csv
import json
import re
import time
from pathlib import Path

import numpy as np
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (
    accuracy_score,
    average_precision_score,
    brier_score_loss,
    confusion_matrix,
    f1_score,
    precision_score,
    recall_score,
    roc_auc_score,
)
from sklearn.pipeline import Pipeline
from sklearn.svm import LinearSVC
from sklearn.calibration import CalibratedClassifierCV

DATA_DIR = Path("data")
PREPARED_DIR = DATA_DIR / "isot_prepared"
OUTPUT_DIR = DATA_DIR / "isot_benchmarks"
RANDOM_SEED = 42

REUTERS_DATELINE_RE = re.compile(r"^[A-Z][A-Za-z\.\s,]{2,40}\(Reuters\)\s*-\s*")


def load_articles():
    rows = {}
    for filename, label in (("True.csv", 0), ("Fake.csv", 1)):
        path = DATA_DIR / filename
        with path.open("r", encoding="utf-8", errors="strict", newline="") as f:
            reader = csv.DictReader(f)
            expected = ["title", "text", "subject", "date"]
            if reader.fieldnames != expected:
                raise ValueError(f"{path}: unexpected schema {reader.fieldnames}")
            for i, row in enumerate(reader):
                rows[f"{'REAL' if label == 0 else 'FAKE'}-{i}"] = {
                    "text": f"{row['title'].strip()} {row['text'].strip()}".strip(),
                    "label": label,
                }
    return rows


def read_ids(name):
    path = PREPARED_DIR / "splits" / f"{name}_ids.txt"
    return [x.strip() for x in path.read_text(encoding="utf-8").splitlines() if x.strip()]


def clean_reuters(text):
    return REUTERS_DATELINE_RE.sub("", text, count=1).strip()


def make_pipeline(model_name, model):
    vectorizer = TfidfVectorizer(
        ngram_range=(1, 2),
        max_features=100000,
        min_df=2,
        sublinear_tf=True,
        strip_accents="unicode",
        stop_words="english",
    )
    if model_name == "calibrated_linear_svm":
        estimator = CalibratedClassifierCV(model, method="sigmoid", cv=3)
    else:
        estimator = model
    return Pipeline([("tfidf", vectorizer), ("model", estimator)])


def probabilities(model, x):
    if hasattr(model, "predict_proba"):
        return model.predict_proba(x)[:, 1]
    scores = model.decision_function(x)
    return 1.0 / (1.0 + np.exp(-np.clip(scores, -50, 50)))


def ece_score(y, p, bins=10):
    edges = np.linspace(0.0, 1.0, bins + 1)
    total = len(y)
    ece = 0.0
    for lo, hi in zip(edges[:-1], edges[1:]):
        mask = (p >= lo) & (p < hi if hi < 1 else p <= hi)
        if not np.any(mask):
            continue
        ece += (mask.sum() / total) * abs(float(np.mean(p[mask])) - float(np.mean(y[mask])))
    return float(ece)


def metric_block(y, p, latency_ms):
    pred = (p >= 0.5).astype(int)
    return {
        "accuracy": float(accuracy_score(y, pred)),
        "precision": float(precision_score(y, pred, zero_division=0)),
        "recall": float(recall_score(y, pred, zero_division=0)),
        "f1": float(f1_score(y, pred, zero_division=0)),
        "macro_f1": float(f1_score(y, pred, average="macro", zero_division=0)),
        "roc_auc": float(roc_auc_score(y, p)),
        "pr_auc": float(average_precision_score(y, p)),
        "brier": float(brier_score_loss(y, p)),
        "ece_10": ece_score(y, p),
        "mean_inference_ms": float(latency_ms),
        "confusion_matrix": confusion_matrix(y, pred).tolist(),
    }


def evaluate(model, x, y):
    start = time.perf_counter()
    p = probabilities(model, x)
    elapsed = (time.perf_counter() - start) * 1000.0
    per_item = elapsed / max(len(x), 1)
    return metric_block(y, p, per_item)


def fit_and_measure(model_name, variant, train_x, train_y, val_x, val_y, test_x, test_y, temporal_x, temporal_y):
    model = make_pipeline(
        model_name,
        LogisticRegression(C=1.0, max_iter=1500, solver="liblinear", random_state=RANDOM_SEED)
        if model_name == "logistic_regression"
        else LinearSVC(C=1.0, random_state=RANDOM_SEED),
    )

    start = time.perf_counter()
    model.fit(train_x, train_y)
    fit_seconds = time.perf_counter() - start

    return {
        "model": model_name,
        "variant": variant,
        "fit_seconds": float(fit_seconds),
        "validation": evaluate(model, val_x, val_y),
        "test": evaluate(model, test_x, test_y),
        "temporal_test": evaluate(model, temporal_x, temporal_y),
    }


def main():
    print("=" * 78)
    print("TRUTHLENS AI - REAL ISOT MODEL BENCHMARK (PHASE 7)")
    print("=" * 78)

    stats_path = PREPARED_DIR / "stats.json"
    if not stats_path.exists():
        raise FileNotFoundError("Run scripts/isot_data_pipeline.py first.")

    articles = load_articles()

    split_ids = {
        "train": read_ids("train"),
        "val": read_ids("val"),
        "test": read_ids("test"),
        "temporal_train": read_ids("temporal_train"),
        "temporal_test": read_ids("temporal_test"),
    }

    def xy(ids, transform):
        x = [transform(articles[i]["text"]) for i in ids]
        y = np.array([articles[i]["label"] for i in ids], dtype=np.int8)
        return x, y

    results = []
    for variant, transform in (
        ("raw", lambda x: x),
        ("reuters_dateline_mitigated", clean_reuters),
    ):
        train_x, train_y = xy(split_ids["train"], transform)
        val_x, val_y = xy(split_ids["val"], transform)
        test_x, test_y = xy(split_ids["test"], transform)
        temporal_x, temporal_y = xy(split_ids["temporal_test"], transform)

        for model_name in ("logistic_regression", "calibrated_linear_svm"):
            print(f"\nBenchmarking {model_name} / {variant} ...")
            result = fit_and_measure(
                model_name,
                variant,
                train_x, train_y,
                val_x, val_y,
                test_x, test_y,
                temporal_x, temporal_y,
            )
            results.append(result)
            print(json.dumps({
                "model": model_name,
                "variant": variant,
                "validation_f1": result["validation"]["f1"],
                "test_f1": result["test"]["f1"],
                "temporal_f1": result["temporal_test"]["f1"],
            }, indent=2))

    output = {
        "phase": 7,
        "dataset": "ISOT Fake News Dataset",
        "random_seed": RANDOM_SEED,
        "production_artifact_modified": False,
        "notes": [
            "Benchmarks use Phase 2 near-duplicate-group-aware splits.",
            "Temporal test is evaluated separately and is not used for model selection.",
            "Reuters dateline ablation measures the effect of the known source shortcut.",
            "This script does not write data/saved_model_artifacts.json.",
        ],
        "results": results,
    }

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    out_path = OUTPUT_DIR / "benchmark.json"
    out_path.write_text(json.dumps(output, indent=2), encoding="utf-8")
    print(f"\nWrote benchmark report: {out_path}")
    print("PHASE 7 BENCHMARK COMPLETE. Production model artifact was not modified.")


if __name__ == "__main__":
    main()
